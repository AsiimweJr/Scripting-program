ITEM: 3
A maid arrived home late in the night. She wanted to prepare a cup of tea in the kitchen. Since it was dark, she lit a candle then lit a charcoal stove and placed there a saucepan containing water and covered with a lid on the stove. A boy at home was with her in the kitchen and observed all what was going on. To his surprise, the size of the candle kept on reducing and the top part of the candle turned to a liquid, though the candle kept lighting. When water boiled, she removed the cover from the saucepan and steam poured out with water droplets forming on the cover. She poured hot water in a cup and later on put a tea bag in the cup. All the water turned brown before even stirring. All these observations puzzled the boy the more.

Task
As a learner of Physics:

(a) Identify the different states of matter in this scenario and give examples.
(b) Using the kinetic theory of matter, explain the arrangement of particles in the state(s) of matter identified in (a) above.
(c) Name the change(s) of state in the scenario.
(d) Explain why all the water in the tea cup turned brown when the tea bag was dropped in the hot water.
